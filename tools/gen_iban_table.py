"""Generate src/iban_table.h for valid_id(type = "iban").

Reads the country BBAN structures of the SWIFT IBAN Registry from the copy
python-stdnum ships (stdnum/iban.dat), so valid_id() checks the same
structures as stdnum.iban.is_valid(x, check_country = False).

Run from the repository root:
    py -I tools/gen_iban_table.py <path to stdnum/iban.dat>
"""

import os
import re
import sys

OUT = os.path.join("src", "iban_table.h")
ELEMENT = re.compile(r"([1-9][0-9]*)!([nac])")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    source = sys.argv[1]
    header = []
    rows = []
    with open(source, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#"):
                header.append(line[1:].strip())
                continue
            m = re.match(r'^([A-Z]{2}) .*bban="([^"]*)"', line)
            if not m:
                continue
            code, bban = m.groups()
            if ELEMENT.sub("", bban):
                sys.exit("unexpected structure for %s: %s" % (code, bban))
            # Expand to one class letter per BBAN character.
            classes = "".join(kind * int(count)
                              for count, kind in ELEMENT.findall(bban))
            rows.append((code, classes))
    rows.sort()

    lines = []
    w = lines.append
    w("// Generated by tools/gen_iban_table.py from python-stdnum's iban.dat:")
    for text in header:
        w("//   " + text)
    w("// Do not edit by hand.")
    w("#ifndef FAST_STRING_IBAN_TABLE_H")
    w("#define FAST_STRING_IBAN_TABLE_H")
    w("")
    w("#include <cstddef>")
    w("")
    w("// Each country's BBAN as one class per character: n digit, a upper-case")
    w("// letter, c letter or digit. The IBAN is the country code, two check")
    w("// digits and the BBAN.")
    w("struct IbanCountry {")
    w("    char code[3];")
    w("    const char* bban;")
    w("};")
    w("")
    w("static const IbanCountry IBAN_COUNTRIES[] = {")
    for code, classes in rows:
        w('    {"%s", "%s"},' % (code, classes))
    w("};")
    w("")
    w("static const std::size_t IBAN_COUNTRY_COUNT =")
    w("    sizeof(IBAN_COUNTRIES) / sizeof(IBAN_COUNTRIES[0]);")
    w("")
    w("#endif // FAST_STRING_IBAN_TABLE_H")

    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s: %d countries" % (OUT, len(rows)))


if __name__ == "__main__":
    main()
