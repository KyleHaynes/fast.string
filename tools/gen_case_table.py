"""Generate src/case_table.h for fupper(), flower() and ftitle_case().

Mappings come from Python's str.upper(), str.lower() and str.title(), which
implement the full, locale-independent Unicode case mappings (UnicodeData
plus SpecialCasing), so one code point can map to several: U+00DF LATIN
SMALL LETTER SHARP S upper-cases to "SS", U+0149 to "'N", U+0130 lower-cases
to "i" plus a combining dot above. ASCII is handled in code, so the table
starts at U+0080.

The Greek final sigma and the Turkish/Lithuanian locale tailorings are
context- or locale-dependent rather than per-code-point, so they are not in
the table; fupper()/flower() apply the final-sigma rule themselves and do
not tailor by locale.

Run from the repository root:  py -I tools/gen_case_table.py
"""

import os
import sys
import unicodedata

OUT = os.path.join("src", "case_table.h")
START = 0x80
MAX_POOL = 0x10000


def main():
    pool = bytearray()
    interned = {}

    def intern(text):
        """Offset and length of `text` in the shared UTF-8 pool."""
        encoded = text.encode("utf-8")
        if encoded not in interned:
            interned[encoded] = len(pool)
            pool.extend(encoded)
        return interned[encoded], len(encoded)

    entries = []
    for cp in range(START, 0x110000):
        ch = chr(cp)
        upper, lower, title = ch.upper(), ch.lower(), ch.title()
        if upper == ch and lower == ch and title == ch:
            continue
        entries.append((cp, intern(upper), intern(lower), intern(title)))

    if len(pool) > MAX_POOL:
        raise SystemExit("pool of %d bytes does not fit a uint16 offset"
                         % len(pool))
    if any(length > 255 for entry in entries for _, length in entry[1:]):
        raise SystemExit("a mapping is longer than 255 bytes")

    lines = [
        "// Generated by tools/gen_case_table.py from the full Unicode case",
        "// mappings of Python %d.%d's str methods (Unicode %s). Do not edit"
        % (sys.version_info[0], sys.version_info[1],
           unicodedata.unidata_version),
        "// by hand.",
        "#ifndef FAST_STRING_CASE_TABLE_H",
        "#define FAST_STRING_CASE_TABLE_H",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "// Case mappings of the code points from U+0080 that have one. Each",
        "// offset and length addresses the UTF-8 bytes of one mapping in",
        "// CASE_POOL; a mapping may be several code points long, and is the",
        "// code point itself where that case leaves it unchanged.",
        "struct CaseEntry {",
        "    std::uint32_t codepoint;",
        "    std::uint16_t upper_offset;  // into CASE_POOL",
        "    std::uint16_t lower_offset;",
        "    std::uint16_t title_offset;",
        "    std::uint8_t upper_length;",
        "    std::uint8_t lower_length;",
        "    std::uint8_t title_length;",
        "};",
        "",
        "static const std::size_t CASE_ENTRY_COUNT = %d;" % len(entries),
        "static const CaseEntry CASE_ENTRIES[] = {",
    ]
    for cp, upper, lower, title in entries:
        lines.append("    {0x%04X, %d, %d, %d, %d, %d, %d},"
                     % (cp, upper[0], lower[0], title[0],
                        upper[1], lower[1], title[1]))
    lines += ["};", "",
              "static const std::size_t CASE_POOL_SIZE = %d;" % len(pool),
              "static const unsigned char CASE_POOL[] = {"]
    for i in range(0, len(pool), 16):
        row = pool[i:i + 16]
        lines.append("    " + " ".join("0x%02X," % b for b in row))
    lines += ["};", "", "#endif  // FAST_STRING_CASE_TABLE_H", ""]

    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))
    print("%s: %d entries, %d pool bytes" % (OUT, len(entries), len(pool)))


if __name__ == "__main__":
    main()
