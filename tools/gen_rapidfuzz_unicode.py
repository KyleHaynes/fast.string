# Generates src/rapidfuzz_unicode.h: RapidFuzz's utils.default_process
# mapping, taken from the files it ships in a RapidFuzz checkout
# (src/rapidfuzz/utils.hpp for code points below 256, and the CPython
# unicodetype_db.h for the rest), as compact runs.
#
#   python tools/gen_rapidfuzz_unicode.py \
#       <RapidFuzz>/src/rapidfuzz/unicodetype_db.h \
#       <RapidFuzz>/src/rapidfuzz/utils.hpp src/rapidfuzz_unicode.h [site-packages]
#
# With a fourth argument, a directory holding an installed rapidfuzz, every
# code point up to U+2FFFF is also checked against
# rapidfuzz.utils.default_process.
import re
import sys

db_path, utils_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
text = open(db_path, encoding="utf-8").read()


def array(name):
    m = re.search(r"%s\[\]\s*=\s*\{(.*?)\};" % re.escape(name), text, re.S)
    return m.group(1)


records = [
    tuple(int(v) for v in rec.split(","))
    for rec in re.findall(r"\{([^{}]*)\}", array("_PyUnicode_TypeRecords"))
]
extended = [int(v, 0) for v in re.findall(r"-?\w+", array("_PyUnicode_ExtendedCase"))]
index1 = [int(v) for v in re.findall(r"\d+", array("index1"))]
index2 = [int(v) for v in re.findall(r"\d+", array("index2"))]
shift = int(re.search(r"#define SHIFT (\d+)", text).group(1))

ALPHA, DECIMAL, DIGIT, NUMERIC, EXTENDED_CASE = 0x01, 0x02, 0x04, 0x800, 0x4000


def record(cp):
    if cp >= 0x110000:
        return records[0]
    i = index1[cp >> shift]
    i = index2[(i << shift) + (cp & ((1 << shift) - 1))]
    return records[i]


def default_process(cp):
    upper, lower, title, decimal, digit, flags = record(cp)
    if not (flags & (ALPHA | DECIMAL | DIGIT | NUMERIC)):
        return 0x20
    if flags & EXTENDED_CASE:
        return extended[lower & 0xFFFF]
    return (cp + lower) & 0xFFFFFFFF


# The table below 256 is copied from RapidFuzz's utils.hpp verbatim.
utils = open(utils_path, encoding="utf-8").read()
m = re.search(r"extended_ascii_mapping\[256\]\s*=\s*\{(.*?)\};", utils, re.S)
latin = [int(v) for v in re.findall(r"\d+", m.group(1))]
assert len(latin) == 256

# Runs over [256, 0x110000): kind 0 = map to space, kind 1 = add a constant
# delta, kind 2 = alternating pairs (even code point + 1, odd one unchanged),
# kind 3 = alternating pairs the other way round (odd + 1, even unchanged).
runs = []
cp = 256
END = 0x110000
values = [default_process(c) for c in range(END)]
while cp < END:
    v = values[cp]
    if v == 0x20:
        e = cp
        while e + 1 < END and values[e + 1] == 0x20:
            e += 1
        runs.append((cp, e, 0, 0))
        cp = e + 1
        continue
    delta = v - cp
    e = cp
    while e + 1 < END and values[e + 1] != 0x20 and values[e + 1] - (e + 1) == delta:
        e += 1
    if e == cp and delta in (0, 1) and cp + 1 < END:
        # Try an alternating run: (+1, 0, +1, 0, ...) starting here.
        parity = cp & 1
        pattern_start_delta = delta
        e2 = cp
        while e2 + 1 < END:
            n = e2 + 1
            if values[n] == 0x20:
                break
            want = pattern_start_delta if ((n - cp) % 2 == 0) else 1 - pattern_start_delta
            if values[n] - n != want:
                break
            e2 = n
        if e2 - cp >= 3:
            # kind 2: code points with the same parity as `cp` get + delta0
            even_gets_one = (parity == 0) == (pattern_start_delta == 1)
            runs.append((cp, e2, 2 if even_gets_one else 3, 0))
            cp = e2 + 1
            continue
    runs.append((cp, e, 1, delta))
    cp = e + 1


def apply(run, c):
    lo, hi, kind, delta = run
    if kind == 0:
        return 0x20
    if kind == 1:
        return c + delta
    if kind == 2:
        return c + 1 if c % 2 == 0 else c
    return c + 1 if c % 2 == 1 else c


# Verify the encoding round-trips every code point.
ri = 0
for c in range(256, END):
    while runs[ri][1] < c:
        ri += 1
    assert apply(runs[ri], c) == values[c], hex(c)

# Merge adjacent space runs never happen (they're maximal); the space runs are
# implicit if we only store non-space runs and default to space. Store only
# non-space runs to halve the table.
kept = [r for r in runs if r[2] != 0]
print("runs:", len(runs), "non-space runs:", len(kept), file=sys.stderr)

with open(out_path, "w", encoding="ascii", newline="\n") as f:
    f.write("// Generated by tools/gen_rapidfuzz_unicode.py from RapidFuzz's\n")
    f.write("// src/rapidfuzz/utils.hpp and unicodetype_db.h (CPython's Unicode\n")
    f.write("// database). Do not edit by hand.\n")
    f.write("#ifndef FAST_STRING_RAPIDFUZZ_UNICODE_H\n")
    f.write("#define FAST_STRING_RAPIDFUZZ_UNICODE_H\n\n")
    f.write("#include <cstddef>\n#include <cstdint>\n\n")
    f.write("// default_process() below U+0100: Python 3.9's\n")
    f.write("// [ord(chr(x).lower()) if chr(x).isalnum() else 0x20 for x in range(256)].\n")
    f.write("static const std::uint8_t rf_latin1_process[256] = {\n")
    for i in range(0, 256, 16):
        f.write("    " + ", ".join("%3d" % v for v in latin[i:i + 16]) + ",\n")
    f.write("};\n\n")
    f.write("// Code points from U+0100 that are alphanumeric, as runs\n")
    f.write("// {first, last, kind, delta}: kind 1 adds delta (the lowercase\n")
    f.write("// mapping), kind 2 adds one to even code points, kind 3 adds one to\n")
    f.write("// odd ones. Every code point outside a run maps to a space.\n")
    f.write("struct RfProcessRun {\n")
    f.write("    std::uint32_t first;\n")
    f.write("    std::uint32_t last;\n")
    f.write("    std::int32_t kind;\n")
    f.write("    std::int32_t delta;\n")
    f.write("};\n\n")
    f.write("static const RfProcessRun rf_process_runs[] = {\n")
    for lo, hi, kind, delta in kept:
        f.write("    {0x%X, 0x%X, %d, %d},\n" % (lo, hi, kind, delta))
    f.write("};\n\n")
    f.write("static const std::size_t rf_process_run_count =\n")
    f.write("    sizeof(rf_process_runs) / sizeof(rf_process_runs[0]);\n\n")
    f.write("#endif // FAST_STRING_RAPIDFUZZ_UNICODE_H\n")

if len(sys.argv) > 4:
    sys.path.insert(0, sys.argv[4])
    from rapidfuzz.utils import default_process as dp
    import random
    random.seed(1)
    bad = 0
    for c in list(range(1, 0xD800)) + list(range(0xE000, 0x30000)):
        s = chr(c)
        got = dp("a" + s + "a")
        want_cp = latin[c] if c < 256 else values[c]
        want = "a" + chr(want_cp) + "a" if want_cp != 0x20 else "a a"
        if got != want:
            bad += 1
            if bad < 10:
                print("mismatch", hex(c), ascii(got), ascii(want), file=sys.stderr)
    print("checked against rapidfuzz.utils.default_process; mismatches:", bad, file=sys.stderr)
