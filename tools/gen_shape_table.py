"""Generate src/shape_table.h for string_shape().

Classes come from the general categories of Python's unicodedata:
  1 upper  Lu, Lt         -> "A"
  2 lower  Ll             -> "a"
  3 letter Lm, Lo         -> "a" (letters without case)
  4 digit  Nd             -> "9"
  5 mark   Mn, Mc, Me     -> dropped (part of the letter before it)
Every other code point is copied unchanged. ASCII is handled in code, so the
table starts at U+0080.

Run from the repository root:  py -I tools/gen_shape_table.py
"""

import os
import sys
import unicodedata

OUT = os.path.join("src", "shape_table.h")
CLASSES = {"Lu": 1, "Lt": 1, "Ll": 2, "Lm": 3, "Lo": 3, "Nd": 4,
           "Mn": 5, "Mc": 5, "Me": 5}


def main():
    runs = []
    for cp in range(0x80, 0x110000):
        cls = CLASSES.get(unicodedata.category(chr(cp)), 0)
        if cls == 0:
            continue
        if runs and runs[-1][1] == cp - 1 and runs[-1][2] == cls:
            runs[-1][1] = cp
        else:
            runs.append([cp, cp, cls])

    lines = []
    w = lines.append
    w("// Generated by tools/gen_shape_table.py from the general categories of")
    w("// Python %d.%d's unicodedata (Unicode %s). Do not edit by hand."
      % (sys.version_info[0], sys.version_info[1], unicodedata.unidata_version))
    w("#ifndef FAST_STRING_SHAPE_TABLE_H")
    w("#define FAST_STRING_SHAPE_TABLE_H")
    w("")
    w("#include <cstddef>")
    w("#include <cstdint>")
    w("")
    w("// Runs of code points from U+0080 with the same class: 1 upper case")
    w("// (Lu, Lt), 2 lower case (Ll), 3 other letters (Lm, Lo), 4 decimal")
    w("// digits (Nd), 5 combining marks (Mn, Mc, Me). Code points outside every")
    w("// run have class 0.")
    w("struct ShapeRun {")
    w("    std::uint32_t first;")
    w("    std::uint32_t last;")
    w("    std::uint8_t kind;")
    w("};")
    w("")
    w("static const ShapeRun SHAPE_RUNS[] = {")
    for first, last, cls in runs:
        w("    {0x%X, 0x%X, %d}," % (first, last, cls))
    w("};")
    w("")
    w("static const std::size_t SHAPE_RUN_COUNT =")
    w("    sizeof(SHAPE_RUNS) / sizeof(SHAPE_RUNS[0]);")
    w("")
    w("#endif // FAST_STRING_SHAPE_TABLE_H")

    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s: %d runs" % (OUT, len(runs)))


if __name__ == "__main__":
    main()
