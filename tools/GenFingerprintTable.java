// Generates src/fingerprint_table.h for fingerprint() and ngram_fingerprint():
// OpenRefine's FingerprintKeyer.normalize(s, true), applied to every code
// point on its own, with the Java runtime's own Unicode tables.
//
//   javac -d <tmp> tools/GenFingerprintTable.java
//   java -cp <tmp> GenFingerprintTable > src/fingerprint_table.h
//
// The steps are OpenRefine's (modules/core/.../clustering/binning/
// FingerprintKeyer.java): lowercase, NFKD, delete combining diacritical
// marks, modifier letters and modifier symbols, map the "non-diacritic"
// letters below, then delete punctuation and non-whitespace control
// characters. Each step works character by character, so a per-code-point
// table reproduces it. Two whole-string effects are not reproduced: Greek
// capital sigma lowercases to the medial form even at the end of a word,
// and combining marks outside U+0300-U+036F keep their input order rather
// than NFKD's canonical order.
import java.nio.charset.StandardCharsets;
import java.text.Normalizer;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.regex.Pattern;

public class GenFingerprintTable {
    static final Pattern PUNCTCTRL = Pattern.compile(
            "\\p{Punct}|[\\x00-\\x08\\x0E-\\x1F\\x7F\\x80-\\x84\\x86-\\x9F]",
            Pattern.UNICODE_CHARACTER_CLASS);
    static final Pattern DIACRITICS_AND_FRIENDS =
            Pattern.compile("[\\p{InCombiningDiacriticalMarks}\\p{IsLm}\\p{IsSk}]+");
    static final Map<String, String> NONDIACRITICS = new HashMap<>();
    static {
        NONDIACRITICS.put("ß", "ss");
        NONDIACRITICS.put("æ", "ae");
        NONDIACRITICS.put("ø", "oe");
        NONDIACRITICS.put("å", "aa");
        NONDIACRITICS.put("©", "c");
        NONDIACRITICS.put("ð", "d");
        NONDIACRITICS.put("đ", "d");
        NONDIACRITICS.put("ɖ", "d");
        NONDIACRITICS.put("þ", "th");
        NONDIACRITICS.put("ƿ", "w");
        NONDIACRITICS.put("ħ", "h");
        NONDIACRITICS.put("ı", "i");
        NONDIACRITICS.put("ĸ", "k");
        NONDIACRITICS.put("ł", "l");
        NONDIACRITICS.put("ŋ", "n");
        NONDIACRITICS.put("ſ", "s");
        NONDIACRITICS.put("ŧ", "t");
        NONDIACRITICS.put("œ", "oe");
        NONDIACRITICS.put("ẜ", "s");
        NONDIACRITICS.put("ẝ", "s");
    }

    static String normalize(String s) {
        s = s.toLowerCase(Locale.ROOT);
        s = Normalizer.normalize(s, Normalizer.Form.NFKD);
        s = DIACRITICS_AND_FRIENDS.matcher(s).replaceAll("");
        StringBuilder b = new StringBuilder();
        for (int i = 0; i < s.length(); i++) {
            String c = s.substring(i, i + 1);
            String r = NONDIACRITICS.get(c);
            b.append(r == null ? c : r);
        }
        return PUNCTCTRL.matcher(b.toString()).replaceAll("");
    }

    public static void main(String[] args) {
        StringBuilder out = new StringBuilder();
        int[] ascii = new int[128];
        List<int[]> entries = new ArrayList<>();
        List<Integer> pool = new ArrayList<>();
        for (int cp = 0; cp <= 0x10FFFF; cp++) {
            if (cp >= 0xD800 && cp <= 0xDFFF) continue;
            String c = new String(Character.toChars(cp));
            String f = normalize(c);
            if (cp < 128) {
                if (f.isEmpty()) ascii[cp] = -1;
                else if (f.length() == 1 && f.charAt(0) < 128) ascii[cp] = f.charAt(0);
                else throw new IllegalStateException("ASCII " + cp + " -> " + f);
                continue;
            }
            if (f.equals(c)) continue;
            if (cp >= 0xAC00 && cp <= 0xD7A3) {
                // Hangul syllables decompose by formula (fingerprint.cpp).
                int index = cp - 0xAC00;
                StringBuilder jamo = new StringBuilder();
                jamo.append((char) (0x1100 + index / 588));
                jamo.append((char) (0x1161 + (index % 588) / 28));
                if (index % 28 != 0) jamo.append((char) (0x11A7 + index % 28));
                if (!jamo.toString().equals(f))
                    throw new IllegalStateException("Hangul " + cp);
                continue;
            }
            byte[] bytes = f.getBytes(StandardCharsets.UTF_8);
            entries.add(new int[] {cp, pool.size(), bytes.length});
            for (byte v : bytes) pool.add(v & 0xFF);
        }
        out.append("#ifndef FAST_STRING_FINGERPRINT_TABLE_H\n");
        out.append("#define FAST_STRING_FINGERPRINT_TABLE_H\n\n");
        out.append("// Generated by tools/GenFingerprintTable.java -- do not edit by hand.\n");
        out.append("// OpenRefine's fingerprint normalisation of each code point, from Java ")
           .append(System.getProperty("java.version")).append(".\n\n");
        out.append("#include <cstddef>\n#include <cstdint>\n\n");
        out.append("// ASCII: the replacement byte, or -1 to delete.\n");
        out.append("static const int FINGERPRINT_ASCII[128] = {\n");
        for (int i = 0; i < 128; i += 16) {
            out.append("   ");
            for (int k = i; k < i + 16; k++) out.append(' ').append(ascii[k]).append(',');
            out.append('\n');
        }
        out.append("};\n\n");
        out.append("struct FingerprintEntry {\n");
        out.append("    std::uint32_t codepoint;\n");
        out.append("    std::uint32_t offset;  // into FINGERPRINT_POOL\n");
        out.append("    std::uint32_t length;  // bytes of UTF-8 output; 0 deletes\n");
        out.append("};\n\n");
        out.append("static const std::size_t FINGERPRINT_ENTRY_COUNT = ").append(entries.size()).append(";\n");
        out.append("static const FingerprintEntry FINGERPRINT_ENTRIES[] = {\n");
        for (int[] e : entries)
            out.append(String.format("    {0x%04X, %d, %d},%n", e[0], e[1], e[2]));
        out.append("};\n\n");
        out.append("static const unsigned char FINGERPRINT_POOL[] = {\n");
        for (int i = 0; i < pool.size(); i += 16) {
            out.append("   ");
            for (int k = i; k < Math.min(pool.size(), i + 16); k++)
                out.append(String.format(" 0x%02X,", pool.get(k)));
            out.append('\n');
        }
        if (pool.isEmpty()) out.append("    0\n");
        out.append("};\n\n#endif // FAST_STRING_FINGERPRINT_TABLE_H\n");
        System.out.print(out.toString().replace(System.lineSeparator(), "\n"));
    }
}
