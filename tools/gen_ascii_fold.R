# Generates src/ascii_fold_table.h for ascii_fold(): ICU's "Latin-ASCII"
# transliteration, read off ICU itself through stringi.
#
#   Rscript tools/gen_ascii_fold.R [src/ascii_fold_table.h]
#
# Every code point is transliterated on its own, and the ones ICU changes
# are written as a sorted table. ICU's rules for Latin-ASCII have no
# right-hand context, so the per-character table reproduces them, except
# for one left-context rule: ICU deletes combining marks that follow a
# Latin-script character or an ASCII digit. The marks it deletes after "e"
# and the Latin-script characters are written as ranges, and the rule is
# checked against ICU for every code point.
out_path <- commandArgs(trailingOnly = TRUE)
if (length(out_path) == 0L) out_path <- "src/ascii_fold_table.h"
stopifnot(requireNamespace("stringi", quietly = TRUE))

cp <- c(0x80:0xD7FF, 0xE000:0x10FFFF)
ch <- intToUtf8(cp, multiple = TRUE)
folded <- stringi::stri_trans_general(ch, "Latin-ASCII")
changed <- folded != ch

after_e <- stringi::stri_trans_general(paste0("e", ch), "Latin-ASCII")
marks <- cp[after_e == "e"]

# The characters that delete following marks: every Latin-script character
# (and the ASCII digits, handled in ascii_fold() itself). Checked below.
latin <- cp[stringi::stri_detect_regex(ch, "\\p{Script=Latin}")]
probe <- c(0x20:0x7F, cp)
probe_ch <- intToUtf8(probe, multiple = TRUE)
absorbs <- stringi::stri_trans_general(paste0(probe_ch, "́"), "Latin-ASCII") ==
    stringi::stri_trans_general(probe_ch, "Latin-ASCII")
expected <- probe %in% c(latin, 0x30:0x39, 0x41:0x5A, 0x61:0x7A)
stopifnot(identical(absorbs, expected))

entries <- data.frame(cp = cp[changed], out = folded[changed],
                      stringsAsFactors = FALSE)
pool <- integer(0)
offset <- integer(nrow(entries))
len <- integer(nrow(entries))
for (i in seq_len(nrow(entries))) {
    bytes <- as.integer(charToRaw(enc2utf8(entries$out[i])))
    offset[i] <- length(pool)
    len[i] <- length(bytes)
    pool <- c(pool, bytes)
}
stopifnot(max(len) < 256, length(pool) < 65536)

as_ranges <- function(v) {
    runs <- split(v, cumsum(c(1, diff(v) != 1)))
    t(vapply(runs, range, numeric(2)))
}
mark_ranges <- as_ranges(marks)
latin_ranges <- as_ranges(latin)

info <- stringi::stri_info()
lines <- c(
    "#ifndef FAST_STRING_ASCII_FOLD_TABLE_H",
    "#define FAST_STRING_ASCII_FOLD_TABLE_H",
    "",
    "// Generated by tools/gen_ascii_fold.R -- do not edit by hand.",
    sprintf("// ICU %s (Unicode %s) Latin-ASCII transliteration, via stringi %s.",
            info$ICU.version, info$Unicode.version,
            as.character(utils::packageVersion("stringi"))),
    "",
    "#include <cstdint>",
    "",
    "struct AsciiFoldEntry {",
    "    std::uint32_t codepoint;",
    "    std::uint16_t offset;  // into ASCII_FOLD_POOL",
    "    std::uint8_t length;   // bytes of UTF-8 output; 0 deletes",
    "};",
    "",
    sprintf("static const std::size_t ASCII_FOLD_ENTRY_COUNT = %d;", nrow(entries)),
    "static const AsciiFoldEntry ASCII_FOLD_ENTRIES[] = {"
)
body <- sprintf("    {0x%04X, %d, %d},", entries$cp, offset, len)
lines <- c(lines, body, "};", "")
pool_lines <- vapply(split(pool, ceiling(seq_along(pool) / 16)), function(v)
    paste0("    ", paste(sprintf("0x%02X,", v), collapse = " ")), "")
lines <- c(lines,
    "static const unsigned char ASCII_FOLD_POOL[] = {", pool_lines, "};", "",
    "// Combining marks deleted after a Latin character or ASCII digit, as",
    "// [first, last].",
    sprintf("static const std::size_t ASCII_FOLD_MARK_RANGE_COUNT = %d;", nrow(mark_ranges)),
    "static const std::uint32_t ASCII_FOLD_MARK_RANGES[][2] = {",
    sprintf("    {0x%04X, 0x%04X},", mark_ranges[, 1], mark_ranges[, 2]),
    "};", "",
    "// Non-ASCII Latin-script characters (Script=Latin), as [first, last].",
    sprintf("static const std::size_t ASCII_FOLD_LATIN_RANGE_COUNT = %d;", nrow(latin_ranges)),
    "static const std::uint32_t ASCII_FOLD_LATIN_RANGES[][2] = {",
    sprintf("    {0x%04X, 0x%04X},", latin_ranges[, 1], latin_ranges[, 2]),
    "};", "",
    "#endif // FAST_STRING_ASCII_FOLD_TABLE_H")
writeLines(lines, out_path, useBytes = TRUE)
cat(sprintf("%d entries, %d pool bytes, %d mark ranges -> %s\n",
            nrow(entries), length(pool), nrow(mark_ranges), out_path))
