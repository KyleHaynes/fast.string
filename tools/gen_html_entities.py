"""Generate src/html_entities.h for html_unescape().

The table is Python's html.entities.html5 (the WHATWG HTML Living Standard's
named character references), and the numeric-reference rules are
html._invalid_charrefs and html._invalid_codepoints, so html_unescape()
reproduces Python's html.unescape().

Run from the repository root:  py -I tools/gen_html_entities.py
"""

import html
import html.entities
import os
import sys

OUT = os.path.join("src", "html_entities.h")


def main():
    names = sorted(html.entities.html5, key=lambda s: s.encode("ascii"))
    pool = []
    offset = 0
    rows = []
    for name in names:
        value = html.entities.html5[name]
        if not 1 <= len(value) <= 2:
            sys.exit("unexpected value length for " + name)
        points = [ord(c) for c in value] + [0]
        rows.append((offset, len(name), points[0], points[1]))
        pool.append(name)
        offset += len(name)
    if offset > 0xFFFF:
        sys.exit("name pool too large for 16-bit offsets")

    invalid_refs = sorted(html._invalid_charrefs.items())
    invalid_points = sorted(html._invalid_codepoints)

    lines = []
    w = lines.append
    w("// Generated by tools/gen_html_entities.py from Python %d.%d's"
      % sys.version_info[:2])
    w("// html.entities.html5 (the WHATWG HTML Living Standard's named character")
    w("// references) and the numeric-reference rules of html.unescape().")
    w("// Do not edit by hand.")
    w("#ifndef FAST_STRING_HTML_ENTITIES_H")
    w("#define FAST_STRING_HTML_ENTITIES_H")
    w("")
    w("#include <cstddef>")
    w("#include <cstdint>")
    w("")
    w("struct HtmlEntity {")
    w("    std::uint16_t offset;  // into HTML_ENTITY_NAMES")
    w("    std::uint8_t length;")
    w("    std::uint32_t first;   // the replacement: one or two code points")
    w("    std::uint32_t second;  // 0 when there is only one")
    w("};")
    w("")
    w("// Every name, including the trailing ';' where it has one, sorted by")
    w("// byte value.")
    w("static const char HTML_ENTITY_NAMES[] =")
    line = '    "'
    for name in pool:
        if len(line) + len(name) > 76:
            w(line + '"')
            line = '    "'
        line += name
    w(line + '";')
    w("")
    w("static const HtmlEntity HTML_ENTITIES[] = {")
    for off, length, a, b in rows:
        w("    {%d, %d, 0x%X, 0x%X}," % (off, length, a, b))
    w("};")
    w("")
    w("static const std::size_t HTML_ENTITY_COUNT =")
    w("    sizeof(HTML_ENTITIES) / sizeof(HTML_ENTITIES[0]);")
    w("")
    w("// Numeric references that HTML maps to another character")
    w("// (html._invalid_charrefs).")
    w("struct HtmlCharref {")
    w("    std::uint32_t number;")
    w("    std::uint32_t point;")
    w("};")
    w("")
    w("static const HtmlCharref HTML_INVALID_CHARREFS[] = {")
    for num, rep in invalid_refs:
        w("    {0x%X, 0x%X}," % (num, ord(rep)))
    w("};")
    w("")
    w("static const std::size_t HTML_INVALID_CHARREF_COUNT =")
    w("    sizeof(HTML_INVALID_CHARREFS) / sizeof(HTML_INVALID_CHARREFS[0]);")
    w("")
    w("// Numeric references that decode to nothing (html._invalid_codepoints),")
    w("// sorted.")
    w("static const std::uint32_t HTML_INVALID_CODEPOINTS[] = {")
    for i in range(0, len(invalid_points), 8):
        chunk = invalid_points[i:i + 8]
        w("    " + " ".join("0x%X," % p for p in chunk))
    w("};")
    w("")
    w("static const std::size_t HTML_INVALID_CODEPOINT_COUNT =")
    w("    sizeof(HTML_INVALID_CODEPOINTS) / sizeof(HTML_INVALID_CODEPOINTS[0]);")
    w("")
    w("#endif // FAST_STRING_HTML_ENTITIES_H")

    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s: %d entities, %d invalid charrefs, %d invalid code points"
          % (OUT, len(rows), len(invalid_refs), len(invalid_points)))


if __name__ == "__main__":
    main()
