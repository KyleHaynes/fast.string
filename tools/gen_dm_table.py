"""Generate src/dm_table.h for daitch_mokotoff() from Apache Commons Codec.

Reads the coding rules of Commons Codec's DaitchMokotoffSoundex (the
`dmrules.txt` resource, Apache License 2.0) and writes them as a C header.
Each rule is a letter sequence and three replacements -- at the start of a
name, before a vowel, and anywhere else -- any of which may offer two
alternatives, written "4|5" in the rules and giving a name two codes.

Four rule patterns are not ASCII (t-cedilla, t-comma, e-ogonek, a-ogonek),
so letters are encoded as bytes: 'a' to 'z' stand for themselves and each
further rule letter takes a byte from 1 up. DM_FOLDS maps every non-ASCII
code point that belongs to one of those letters -- the foldings listed in
the rules, plus every code point that lower-cases into the alphabet, as
Commons Codec lower-cases its input before folding it.

Usage, from the repository root, with the rules file downloaded from
https://github.com/apache/commons-codec (src/main/resources/org/apache/
commons/codec/language/dmrules.txt):

    py -I tools/gen_dm_table.py path/to/dmrules.txt
"""

import os
import re
import sys
import unicodedata

OUT = os.path.join("src", "dm_table.h")
RULE_RE = re.compile(r'^"([^"]*)"\s+"([^"]*)"\s+"([^"]*)"\s+"([^"]*)"\s*$')
FOLD_RE = re.compile(r"^(\S)=(\S)$")


def strip_marks(text):
    """`text` without combining marks, which Java's 1:1 lower case has none of."""
    return "".join(c for c in text if not unicodedata.category(c).startswith("M"))


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    rules, folds = [], {}
    with open(sys.argv[1], encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith(("//", "/*", "*", "*/")):
                continue
            match = RULE_RE.match(line)
            if match:
                rules.append(match.groups())
                continue
            match = FOLD_RE.match(line)
            if match:
                folds[match.group(1)] = match.group(2)
                continue
            raise SystemExit("unparsed rule line: %r" % line)

    # Letters: 'a' to 'z' keep their own byte, every other rule letter takes
    # the next byte from 1 up.
    extra = sorted({c for pattern, _, _, _ in rules for c in pattern
                    if not ("a" <= c <= "z")})
    if len(extra) > 26:
        raise SystemExit("too many non-ASCII rule letters to encode")
    letters = [chr(ord("a") + i) for i in range(26)] + extra
    encode = {c: c for c in letters[:26]}
    encode.update({c: chr(1 + i) for i, c in enumerate(extra)})

    for pattern, *replacements in rules:
        for replacement in replacements:
            for alternative in replacement.split("|"):
                if not alternative.isdigit() and alternative != "":
                    raise SystemExit("rule %r has replacement %r"
                                     % (pattern, replacement))

    # Every code point that belongs to one of the letters: the foldings of the
    # rules file, and anything that lower-cases into the alphabet.
    alphabet = {c: c for c in letters}
    mapped = {}
    for source, target in folds.items():
        if target not in alphabet:
            raise SystemExit("folding %r maps outside the alphabet" % source)
        mapped[ord(source)] = target
    for cp in range(0x80, 0x30000):
        ch = chr(cp)
        if not ch.isalpha():
            continue
        lower = strip_marks(ch.lower())
        letter = mapped.get(ord(lower)) if len(lower) == 1 else None
        if letter is None and len(lower) == 1 and lower in alphabet:
            letter = lower
        if letter is not None:
            mapped.setdefault(cp, letter)

    # Longest pattern first, so the first rule that matches is the one to use.
    rules.sort(key=lambda rule: (rule[0][0], -len(rule[0]), rule[0]))
    groups = {}
    for index, rule in enumerate(rules):
        groups.setdefault(encode[rule[0][0]], []).append(index)
    order = []
    starts = []
    for letter in letters:
        starts.append(len(order))
        order.extend(groups.get(encode[letter], []))
    starts.append(len(order))

    def alternatives(replacement):
        parts = replacement.split("|")
        first = '"%s"' % parts[0]
        second = '"%s"' % parts[1] if len(parts) > 1 else "nullptr"
        if len(parts) > 2:
            raise SystemExit("replacement %r has more than two alternatives"
                             % replacement)
        return "{%s, %s}" % (first, second)

    lines = [
        "// Generated by tools/gen_dm_table.py from the Daitch-Mokotoff coding",
        "// rules of Apache Commons Codec (dmrules.txt, Apache License 2.0).",
        "// Do not edit by hand.",
        "#ifndef FAST_STRING_DM_TABLE_H",
        "#define FAST_STRING_DM_TABLE_H",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "// Letters are bytes: 'a' to 'z' themselves, and %d more from 1 up"
        % len(extra),
        "// (%s)." % ", ".join("\\x%02X = U+%04X" % (1 + i, ord(c))
                               for i, c in enumerate(extra)),
        "static const std::size_t DM_LETTER_COUNT = %d;" % len(letters),
        "static const std::size_t DM_MAX_CODE_LENGTH = 6;",
        "",
        "// One replacement, with the second alternative null unless the rule",
        "// gives a name two codes. An empty alternative codes nothing.",
        "struct DmReplacement {",
        "    const char* first;",
        "    const char* second;",
        "};",
        "",
        "struct DmRule {",
        "    const char* pattern;  // encoded letters, longest first per letter",
        "    std::uint8_t length;",
        "    DmReplacement at_start;",
        "    DmReplacement before_vowel;",
        "    DmReplacement other;",
        "};",
        "",
        "static const std::size_t DM_RULE_COUNT = %d;" % len(rules),
        "static const DmRule DM_RULES[] = {",
    ]
    for index in order:
        pattern, at_start, before_vowel, other = rules[index]
        encoded = "".join(
            c if "a" <= c <= "z" else "\\%03o" % ord(encode[c]) for c in pattern
        )
        lines.append('    {"%s", %d, %s, %s, %s},'
                     % (encoded, len(pattern), alternatives(at_start),
                        alternatives(before_vowel), alternatives(other)))
    lines += ["};", "",
              "// Rules for letter `k` are DM_RULES[DM_RULE_FIRST[k]] up to",
              "// DM_RULE_FIRST[k + 1], longest pattern first.",
              "static const std::uint16_t DM_RULE_FIRST[] = {"]
    lines.append("    " + " ".join("%d," % value for value in starts))
    lines += ["};", "",
              "// A non-ASCII code point and the letter it belongs to.",
              "struct DmFold {",
              "    std::uint32_t codepoint;",
              "    char letter;",
              "};",
              "",
              "static const std::size_t DM_FOLD_COUNT = %d;" % len(mapped),
              "static const DmFold DM_FOLDS[] = {"]
    for cp in sorted(mapped):
        letter = encode[mapped[cp]]
        shown = ("'%s'" % letter if "a" <= letter <= "z"
                 else "'\\%03o'" % ord(letter))
        lines.append("    {0x%04X, %s},  // %s" % (cp, shown,
                                                   unicodedata.name(chr(cp), "")))
    lines += ["};", "", "#endif  // FAST_STRING_DM_TABLE_H", ""]

    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))
    print("%s: %d rules, %d letters, %d folded code points"
          % (OUT, len(rules), len(letters), len(mapped)))


if __name__ == "__main__":
    main()
